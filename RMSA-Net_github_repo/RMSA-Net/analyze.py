def fmt(m, s, k):
    d = DIG.get(k, 3)
    if np.isnan(m):
        return "—"
    return f"{m:.{d}f} ± {s:.{d}f}" if not np.isnan(s) else f"{m:.{d}f}"


def cell(df, run, test, k):
    if k not in df.columns:
        return np.nan, np.nan, 0
    x = df[(df.run == run) & (df.test == test)][k].astype(float)
    if len(x) == 0:
        return np.nan, np.nan, 0
    return x.mean(), x.std(ddof=1) if len(x) > 1 else np.nan, len(x)


def table(df, title, rows, cols, note=""):
    """rows: list of (label, run, test). Returns (markdown, latex, dataframe)."""
    recs = []
    for label, run, test in rows:
        r = {"Condition": label}
        n = 0
        for k in cols:
            m, s, n = cell(df, run, test, k)
            r[HDR.get(k, k)] = fmt(m, s, k)
            r["_" + k] = m
        r["n seeds"] = n
        recs.append(r)
    t = pd.DataFrame(recs)
    show = t[[c for c in t.columns if not c.startswith("_")]]
    show = show[show["n seeds"] > 0]
    md = f"### {title}\n\n" + (show.to_markdown(index=False) if len(show) else "_no runs yet_") + (f"\n\n{note}\n" if note else "\n")
    tex = ""
    if len(show):
        tex = f"% {title}\n\\begin{{tabular}}{{l{'c' * (len(show.columns) - 1)}}}\n\\hline\n"
        tex += " & ".join(show.columns).replace("±", "$\\pm$").replace("↓", "$\\downarrow$").replace("↑", "$\\uparrow$") + " \\\\\n\\hline\n"
        for _, r in show.iterrows():
            tex += " & ".join(str(v) for v in r.values).replace("±", "$\\pm$") + " \\\\\n"
        tex += "\\hline\n\\end{tabular}\n\n"
    t.attrs['show'] = show
    return md, tex, t


def paired(df, a, b, metric="mae", label=""):
    """a, b = (run, test). Pairs by seed."""
    A = df[(df.run == a[0]) & (df.test == a[1])].set_index("seed")[metric]
    B = df[(df.run == b[0]) & (df.test == b[1])].set_index("seed")[metric]
    s = A.index.intersection(B.index)
    if len(s) < 2:
        return None
    d = (A[s] - B[s]).astype(float).values
    t, p = stats.ttest_rel(A[s].values, B[s].values)
    ci = stats.t.interval(0.95, len(d) - 1, loc=d.mean(), scale=stats.sem(d)) if d.std() > 0 else (d.mean(), d.mean())
    return dict(comparison=label, metric=metric, A=f"{a[0]} @ {a[1]}", B=f"{b[0]} @ {b[1]}", n=len(s),
                mean_A=A[s].mean(), mean_B=B[s].mean(), diff=d.mean(), ci_low=ci[0], ci_high=ci[1], t=t, p=p,
                A_better_in=int((d < 0).sum() if metric == "mae" else (d > 0).sum()))


