def bert_tokens_to_words(ex, L):
    """If the export carries BERT token ids, rebuild words exactly: drop [CLS]/[SEP]/[PAD], merge '##' word pieces.
    Word weight = sum of its pieces' alpha (attention mass on the word); |p| = max over pieces."""
    if not ex or not ex[0].get("token_ids"):
        return ex
    try:
        from transformers import BertTokenizer
        tok = BertTokenizer.from_pretrained("bert-base-uncased")
    except Exception as e:
        L.append(f"_Could not load the BERT tokenizer ({e}); install transformers to map tokens to words._\n")
        return ex
    out = []
    for e in ex:
        if e["alpha"] is None:
            out.append(e); continue
        toks = tok.convert_ids_to_tokens(e["token_ids"])
        words, al, ap = [], [], []
        for t, a, p in zip(toks, e["alpha"], e["abs_p"]):
            if t in ("[CLS]", "[SEP]", "[PAD]"):
                continue
            if t.startswith("##") and words:
                words[-1] += t[2:]; al[-1] += a; ap[-1] = max(ap[-1], p)
            else:
                words.append(t); al.append(a); ap.append(p)
        tot = sum(al) or 1.0
        out.append(dict(e, words=words, alpha=[x / tot for x in al], abs_p=ap,
                        special_mass=1.0 - sum(al)))
    sm = np.mean([e.get("special_mass", 0) for e in out])
    L.append(f"Token-to-word mapping uses the BERT token ids stored in the data file. On average {sm * 100:.1f}% of PSG weight "
             f"falls on [CLS]/[SEP] tokens; word weights below are renormalised over real words.\n")
    return out


def psg_analysis(df, out):
    L = ["# PSG analysis (R1.6, R2.8)\n"]
    if "psg_signflip_maxdiff" in df:
        v = df["psg_signflip_maxdiff"].dropna()
        if len(v):
            L.append(f"**Sign-flip check.** Negating the last layer of the polarity estimator changed the regression output by at most "
                     f"{v.max():.2e} over {len(v)} trained models (float rounding only). The sign of p is therefore not identifiable; only |p| is meaningful.\n")
    js = sorted(glob.glob(os.path.join(out, "examples_mosi_rmsa-PCM_tr0.3-0.3_s*_psg.json"))) or sorted(glob.glob(os.path.join(out, "examples_mosi_*_psg.json")))
    if not js:
        open(os.path.join(out, "psg_analysis.md"), "w").write("\n".join(L)); return
    ex = json.load(open(js[0]))
    ex = bert_tokens_to_words(ex, L)
    if ex and ex[0]["words"] is not None:
        try:
            from vaderSentiment.vaderSentiment import SentimentIntensityAnalyzer
            lex = SentimentIntensityAnalyzer().lexicon
            xs, ys, used = [], [], 0
            for e in ex:
                if e["abs_p"] is None or e["words"] is None or len(e["words"]) != len(e["abs_p"]):
                    continue
                used += 1
                for w, p in zip(e["words"], e["abs_p"]):
                    w = w.lower().strip(".,!?\"'")
                    if w in lex:
                        xs.append(p); ys.append(abs(lex[w]))
            if len(xs) > 10:
                rho, pv = stats.spearmanr(xs, ys)
                L.append(f"**|p| vs. VADER lexicon intensity.** Spearman ρ = {rho:.3f} (p = {pv:.2g}) over {len(xs)} lexicon tokens in {used} "
                         f"test utterances whose word count matches the token count. The lexicon is used only for this analysis.\n")
        except ImportError:
            L.append("_Install vaderSentiment (`pip install vaderSentiment`) to compute the lexicon correlation._\n")
        L.append("**Qualitative examples (top-3 tokens by PSG weight).**\n")
        exs = sorted([e for e in ex if e["words"] and e["alpha"] and len(e["words"]) == len(e["alpha"])], key=lambda e: -abs(e["label"]))[:4]
        exs += sorted([e for e in ex if e["words"] and e["alpha"] and len(e["words"]) == len(e["alpha"])], key=lambda e: -abs(e["label"] - e["pred"]))[:2]
        for e in exs:
            top = np.argsort(e["alpha"])[::-1][:3]
            L.append(f"- label {e['label']:+.1f}, prediction {e['pred']:+.2f}: “{' '.join(e['words'])}” → top tokens: "
                     + ", ".join(f"{e['words'][i]} ({e['alpha'][i]:.2f})" for i in top) + "\n")
        try:
            import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
            sel = exs[:4]
            if sel:
                fig, axs = plt.subplots(len(sel), 1, figsize=(10, 1.5 * len(sel)))
                axs = np.atleast_1d(axs)
                for ax, e in zip(axs, sel):
                    ax.bar(range(len(e["alpha"])), e["alpha"], color="#4C72B0")
                    ax.set_xticks(range(len(e["words"]))); ax.set_xticklabels(e["words"], rotation=60, fontsize=7)
                    ax.set_ylabel("α", fontsize=8); ax.set_title(f"label {e['label']:+.1f}, prediction {e['pred']:+.2f}", fontsize=8)
                fig.tight_layout(); fig.savefig(os.path.join(out, "fig6_psg.png"), dpi=200); plt.close(fig)
        except Exception as ex:
            L.append(f"_Figure 6 not drawn: {ex}_\n")
    else:
        L.append("_The data file has no raw_text, so tokens cannot be mapped to words. Use the MMSA release (contains raw_text) for this analysis._\n")
    open(os.path.join(out, "psg_analysis.md"), "w").write("\n".join(L))


